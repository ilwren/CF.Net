/// <summary>Query filters for <c>GET /zones/{zone_id}/dns_records</c>.</summary>
public sealed class DnsRecordListParameters : CloudflarePagedParameters
{
    /// <summary>Filter by record type.</summary>
    public string? Type { get; set; }

    /// <summary>Filter by record name.</summary>
    public string? Name { get; set; }

    /// <summary>Filter by record content.</summary>
    public string? Content { get; set; }

    /// <summary>Field to sort by: <c>type</c>, <c>name</c>, <c>content</c>, <c>ttl</c>, <c>proxied</c>.</summary>
    public string? Order { get; set; }

    /// <summary>Sort direction.</summary>
    public SortDirection? Direction { get; set; }

    /// <summary>Filter by proxied state.</summary>
    public bool? Proxied { get; set; }

    /// <summary>Filter by a single tag.</summary>
    public string? Tag { get; set; }

    /// <summary>Filter by several tags; repeated <c>tag</c> parameters.</summary>
    public IReadOnlyList<string>? Tags { get; set; }

    /// <summary>How tags are combined: <c>all</c> (default) or <c>any</c>.</summary>
    public FilterMatchMode? TagMatch { get; set; }

    /// <summary>How all filters are combined.</summary>
    public FilterMatchMode? Match { get; set; }

    /// <summary>Search across name and content.</summary>
    public string? Search { get; set; }

    /// <inheritdoc />
    public override void Apply(QueryStringBuilder query)
    {
        base.Apply(query);
        query.AddIfNotEmpty("type", Type);
        query.AddIfNotEmpty("name", Name);
        query.AddIfNotEmpty("content", Content);
        query.AddIfNotEmpty("order", Order);
        if (Direction.HasValue)
        {
            query.Add("direction", QueryEnums.ToWire(Direction.Value));
        }

        query.Add("proxied", Proxied);
        query.AddIfNotEmpty("tag", Tag);
        query.AddMany("tag", Tags);
        if (TagMatch.HasValue)
        {
            query.Add("tag_match", QueryEnums.ToWire(TagMatch.Value));
        }

        if (Match.HasValue)
        {
            query.Add("match", QueryEnums.ToWire(Match.Value));
        }

        query.AddIfNotEmpty("search", Search);
    }
}

