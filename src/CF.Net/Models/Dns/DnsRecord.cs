using System.Text.Json;
using System.Text.Json.Serialization;
using CFNet.Http;
using CFNet.Models.Common;

namespace CFNet.Models.Dns;

/// <summary>
/// A DNS record inside a zone. The same type is used for responses and for create/update request
/// bodies: members left <c>null</c> are omitted from the JSON, so a partially filled instance is a
/// valid <c>PATCH</c> payload.
/// </summary>
public sealed class DnsRecord
{
    /// <summary>Record identifier.</summary>
    [JsonPropertyName("id")]
    public string? Id { get; set; }

    /// <summary>Zone the record belongs to.</summary>
    [JsonPropertyName("zone_id")]
    public string? ZoneId { get; set; }

    /// <summary>Name of the zone, e.g. <c>example.com</c>.</summary>
    [JsonPropertyName("zone_name")]
    public string? ZoneName { get; set; }

    /// <summary>
    /// Fully qualified record name. Use <c>@</c> or the zone apex name for the root record.
    /// </summary>
    [JsonPropertyName("name")]
    public string? Name { get; set; }

    /// <summary>Record type. See <see cref="DnsRecordTypes"/> for the literals Cloudflare accepts.</summary>
    [JsonPropertyName("type")]
    public string? Type { get; set; }

    /// <summary>
    /// Record value. Required for simple record types; mutually exclusive with <see cref="Data"/>
    /// for the structured types (SRV, LOC, CAA, CERT).
    /// </summary>
    [JsonPropertyName("content")]
    public string? Content { get; set; }

    /// <summary>Whether this record type can be proxied at all.</summary>
    [JsonPropertyName("proxiable")]
    public bool? Proxiable { get; set; }

    /// <summary>Whether traffic for this record goes through the Cloudflare proxy.</summary>
    [JsonPropertyName("proxied")]
    public bool? Proxied { get; set; }

    /// <summary>
    /// TTL in seconds. <c>1</c> means "automatic". Required when <see cref="Proxied"/> is <c>false</c>.
    /// </summary>
    [JsonPropertyName("ttl")]
    public int? Ttl { get; set; }

    /// <summary>Priority, for MX and SRV records.</summary>
    [JsonPropertyName("priority")]
    public int? Priority { get; set; }

    /// <summary>
    /// Structured record data used instead of <see cref="Content"/> by SRV, LOC, CAA and CERT records.
    /// Deserialised as a <see cref="JsonElement"/>; use <see cref="GetData{T}"/> to project it, or assign
    /// a typed object such as <see cref="DnsRecordSrvData"/> when sending a request.
    /// </summary>
    [JsonPropertyName("data")]
    public object? Data { get; set; }

    /// <summary>Record settings, e.g. CNAME flattening.</summary>
    [JsonPropertyName("settings")]
    public DnsRecordSettings? Settings { get; set; }

    /// <summary>Record metadata reported by Cloudflare.</summary>
    [JsonPropertyName("meta")]
    public DnsRecordMeta? Meta { get; set; }

    /// <summary>Optional note shown in the dashboard.</summary>
    [JsonPropertyName("comment")]
    public string? Comment { get; set; }

    /// <summary>Deprecated plural alias of <see cref="Comment"/>, still returned by the API.</summary>
    [JsonPropertyName("comments")]
    public string? Comments { get; set; }

    /// <summary>Whether the comment was generated by Cloudflare rather than the user.</summary>
    [JsonPropertyName("is_system_comment")]
    public bool? IsSystemComment { get; set; }

    /// <summary>Tags attached to the record.</summary>
    [JsonPropertyName("tags")]
    public List<string>? Tags { get; set; }

    /// <summary>Display names of the tags attached to the record.</summary>
    [JsonPropertyName("tag_names")]
    public List<string>? TagNames { get; set; }

    /// <summary>Creation timestamp.</summary>
    [JsonPropertyName("created_on")]
    public DateTimeOffset? CreatedOn { get; set; }

    /// <summary>Last modification timestamp.</summary>
    [JsonPropertyName("modified_on")]
    public DateTimeOffset? ModifiedOn { get; set; }

    /// <summary>Captures any field Cloudflare adds in the future.</summary>
    [JsonExtensionData]
    public IDictionary<string, JsonElement>? AdditionalData { get; set; }

    /// <summary>
    /// Projects <see cref="Data"/> onto a typed model. Returns <c>null</c> when the record has no
    /// structured data.
    /// </summary>
    /// <typeparam name="T">Target type, e.g. <see cref="DnsRecordSrvData"/>.</typeparam>
    public T? GetData<T>()
    {
        return Data switch
        {
            null => default,
            T typed => typed,
            JsonElement element when element.ValueKind == JsonValueKind.Object => element.Deserialize<T>(Serialization.CloudflareJson.Default),
            JsonElement => default,
            _ => JsonSerializer.Deserialize<T>(JsonSerializer.Serialize(Data, Serialization.CloudflareJson.Default), Serialization.CloudflareJson.Default),
        };
    }

    /// <inheritdoc />
    public override string ToString() => $"{Type} {Name} -> {Content ?? "(structured data)"}";
}

